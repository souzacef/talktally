const messages: Record<AppLocale, Record<TransactionMessageKey, string>> = {
  'en-US': enUS,
  'pt-BR': ptBR,
}

const countMessages = {
  'en-US': {
    records: { one: '{count} record', other: '{count} records' },
    installments: { one: '{count} installment', other: '{count} installments' },
  },
  'pt-BR': {
    records: { one: '{count} registro', other: '{count} registros' },
    installments: { one: '{count} parcela', other: '{count} parcelas' },
  },
} as const

type TransactionCountMessageKey = keyof (typeof countMessages)['en-US']

function interpolate(message: string, params?: Record<string, string | number>): string {
  if (!params) return message
  return message.replace(/\{(\w+)\}/g, (match, key: string) => (
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match
  ))
}

export function transactionText(
  locale: AppLocale,
  key: TransactionMessageKey,
  params?: Record<string, string | number>,
): string {
  return interpolate(messages[locale][key], params)
}

export function transactionCountText(
  locale: AppLocale,
  key: TransactionCountMessageKey,
  count: number,
): string {
  return formatPluralMessage(locale, count, countMessages[locale][key])
}

export function transactionKindLabel(kind: TransactionKind, locale: AppLocale): string {
  const labels: Record<TransactionKind, Record<AppLocale, string>> = {
    INCOME: { 'en-US': 'Income', 'pt-BR': 'Renda' },
    EXPENSE: { 'en-US': 'Expense', 'pt-BR': 'Despesa' },
    REIMBURSEMENT_RECEIPT: { 'en-US': 'Reimbursement', 'pt-BR': 'Reembolso' },
  }
  return labels[kind][locale]
}

export function transactionSourceLabel(source: TransactionSource, locale: AppLocale): string {
  const labels: Record<TransactionSource, Record<AppLocale, string>> = {
    MANUAL: { 'en-US': 'Manual', 'pt-BR': 'Manual' },
    ASSISTANT_TEXT: { 'en-US': 'Assistant', 'pt-BR': 'Assistente' },
    VOICE: { 'en-US': 'Voice', 'pt-BR': 'Voz' },
  }
  return labels[source][locale]
}
